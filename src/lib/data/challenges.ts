export function getBirthdayChallengeSet(age?: number): Challenge[] {
  const exclusive = CHALLENGES.filter((c) => c.isBirthdayExclusive);
  const pool = CHALLENGES.filter((c) => !c.isBirthdayExclusive);
  const shuffled = [...pool].sort(() => Math.random() - 0.5).slice(0, 6);
  const set = [...exclusive, ...shuffled];
  if (age) {
    return set.map((c) =>
      c.id === "c-91"
        ? { ...c, description: `Ein Shot für jedes Lebensjahr (max. 10 von ${age}) – im Staffel-Modus.` }
        : c
    );
  }
  return set;
}
